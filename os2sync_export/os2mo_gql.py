def convert_and_filter(
    settings: Settings,
    fk_org_users: list[ReadUserITAccountsEmployeesObjectsCurrentFkOrgUuids],
    it_users: list[ReadUserITAccountsEmployeesObjectsCurrentItusers],
) -> tuple[
    list[User],
    list[ReadUserITAccountsEmployeesObjectsCurrentItusers],
    set[UUID],
    set[UUID],
]:
    # Find users to delete from fk-org
    delete_fk_org_users = {
        UUID(fk_org_user.external_id)
        for fk_org_user in fk_org_users
        if fk_org_user.user_key not in {a.external_id for a in it_users}
    }
    # Find it-users to delete from MO
    delete_mo_it_users = {
        fk_org_user.uuid
        for fk_org_user in fk_org_users
        if fk_org_user.user_key not in {a.external_id for a in it_users}
    }
    # Map user-keys to uuids using uuids from FK-org it account if it exists, else use the it-users external id (eg objectGUID)
    fk_org_uuids = {
        it.external_id: UUID(
            only({f.external_id for f in fk_org_users if f.user_key == it.external_id})
            or it.external_id
        )
        for it in it_users
    }
    os2sync_updates = []
    for it_user in it_users:
        try:
            os2sync_updates.append(
                convert_to_os2sync(
                    settings=settings,
                    it=it_user,
                    uuid=fk_org_uuids[it_user.external_id],
                )
            )
        except NoPositionError:
            delete_fk_org_users.add(fk_org_uuids[it_user.external_id])
            for fk_org_user in fk_org_users:
                if fk_org_user.user_key == it_user.external_id:
                    delete_mo_it_users.add(fk_org_user.uuid)
    # Find it-users to create in MO
    new_mo_it_users = [
        u for u in it_users if u.external_id not in {f.user_key for f in fk_org_users}
    ]

    return os2sync_updates, new_mo_it_users, delete_fk_org_users, delete_mo_it_users


def choose_public_address(
    candidates: Iterable[ReadUserITAccountsEmployeesObjectsCurrentItusersEmail]
    | Iterable[ReadUserITAccountsEmployeesObjectsCurrentItusersMobile]
    | Iterable[ReadUserITAccountsEmployeesObjectsCurrentItusersLandline],
    priority: list[UUID],
) -> str | None:
    if not candidates:
        return None
    # Filter visibility
    candidates_filtered = [
        c for c in candidates if c.visibility is None or c.visibility.scope == "PUBLIC"
    ]
    # Filter address_type
    candidates_filtered = [
        c for c in candidates_filtered if c.address_type.uuid in priority
    ]
    res = min(
        candidates_filtered,
        key=lambda p: priority.index(p.address_type.uuid),
        default=None,
    )

    return res.value if res else None


def convert_to_os2sync(
    settings: Settings,
    it: ReadUserITAccountsEmployeesObjectsCurrentItusers,
    uuid: UUID,
) -> User:
    if it.person is None:
        raise ValueError(
            "The given it-account has no 'person' connected and is therefore invalid."
        )
    mo_person = one(it.person)
    cpr = mo_person.cpr_number if settings.sync_cpr else None
    person = Person(
        Name=mo_person.nickname
        if mo_person.nickname and settings.use_nickname
        else mo_person.name,
        Cpr=cpr,
    )

    landline = choose_public_address(it.landline, settings.landline_scope_classes)
    mobile = choose_public_address(it.mobile, settings.phone_scope_classes)
    email = choose_public_address(it.email, settings.email_scope_classes)

    mo_engagements = []
    positions = []

    if it.engagements_responses and it.engagements_responses.objects:
        # Filter engagements in irrelevant units
        mo_engagements = [
            e
            for e in it.engagements_responses.objects
            if e
            and e.validities
            and filter_relevant_orgunit(
                settings=settings, orgunit_data=one(first(e.validities).org_unit)
            )
        ]
    for i in mo_engagements:
        if i.validities and i.startdates:
            # There might be other validities in the future but can only sync the first
            eng = first(i.validities)
            # Job title can be read from an extension field if configured to do so.
            if settings.extension_field_as_job_function == ExtensionField.EXTENSION_1:
                extension_value = eng.extension_1
            elif settings.extension_field_as_job_function == ExtensionField.EXTENSION_3:
                extension_value = eng.extension_3
            else:
                extension_value = None
            name = extension_value or eng.job_function.name
            # Org units can be mapped to other uuids in fk-org by adding an it-user to the unit in MO
            org_unit_uuid = (
                UUID(first(one(eng.org_unit).itusers).user_key)
                if one(eng.org_unit).itusers
                else one(eng.org_unit).uuid
            )
            # Original startdate of the engagement
            start_date = min([s.validity.from_ for s in i.startdates])

            positions.append(
                Position(Name=name, OrgUnitUuid=org_unit_uuid, StartDate=start_date)
            )

    return User(
        Uuid=uuid,
        UserId=it.user_key,
        Person=person,
        Positions=positions,
        PhoneNumber=mobile,
        Landline=landline,
        Email=email,
    )


async def find_past_account_uuid(
    graphql_client: GraphQLClient,
    person_uuid: UUID,
    it: ReadUserITAccountsEmployeesObjectsCurrentItusers,
    current_fk_uuids: set[UUID],
    it_system_user_keys: list[str],
) -> UUID | None:
    """Check if user has had an fk-org account in the past for a different AD-account with the same SamAccountName"""

    # Read all AD accounts with the given SamAccountName
    past_ad_account = await graphql_client.find_past_i_t_user(
        filter=ITUserFilter(
            employee=EmployeeFilter(uuids=[person_uuid]),  # type: ignore[call-arg]
            user_keys=[it.user_key],
            itsystem=ITSystemFilter(user_keys=it_system_user_keys),  # type: ignore[call-arg]
            from_date=None,
            to_date=None,
        ),
        start=None,
        end=datetime.now(tz=UTC),
    )
    # There might be several instances of an AD account having the same account name
    past_ad_objectguids = list(
        {
            v.external_id
            for a in past_ad_account.objects
            for v in a.validities
            if v.external_id
        }
    )
    # Find every fk-org account which has an user_key that matches one of the found external_ids.
    past_fk_org_accounts = await graphql_client.find_past_i_t_user(
        filter=ITUserFilter(
            employee=EmployeeFilter(uuids=[person_uuid]),  # type: ignore[call-arg]
            user_keys=past_ad_objectguids,
            itsystem=ITSystemFilter(user_keys=["FK-ORG-UUID", "FK-ORG UUID"]),  # type: ignore[call-arg]
            from_date=None,
            to_date=None,
        ),
        end=datetime.now(tz=UTC),
    )
    # Return the latest fk-org uuid that matches. Return None if no matches are found.
    if not past_fk_org_accounts.objects:
        return None
    past_fk_org_validities = [
        validity
        for ituser in past_fk_org_accounts.objects
        for validity in ituser.validities
        if validity.external_id not in current_fk_uuids
    ]
    if not past_fk_org_validities:
        return None

    max_date = datetime.max.replace(tzinfo=UTC)

    latest = max(
        past_fk_org_validities,
        # Replace empty validities with datetime.max to allow comparison
        key=lambda v: v.validity.to or max_date,
    )
    return UUID(latest.external_id) if latest.external_id else None


@handle_exclusively_decorator(key=lambda uuid, *_, **__: uuid)
async def sync_mo_user_to_fk_org(
    uuid: UUID,
    graphql_client: GraphQLClient,
    settings: Settings,
    os2sync_client: OS2SyncClient,
    dry_run: bool = False,
) -> tuple[list[User], set[UUID]]:
    """Handles sync of a persons users to fk-org.

    Returns a list of users synced to fk-org and a set of uuids representing users deleted from fk-org.
    """
    fk_org_users, it_users = await read_fk_users_from_person(
        graphql_client=graphql_client,
        uuid=uuid,
        it_user_keys=settings.it_system_user_keys,
        email=settings.email_scope_classes,
        mobile=settings.phone_scope_classes,
        landline=settings.landline_scope_classes,
    )
    logger.info(
        "Found the following itusers",
        uuid=uuid,
        fk_org_users=fk_org_users,
        ad_users=it_users,
    )
    fk_org_uuids = [f.external_id for f in fk_org_users]
    if len(fk_org_uuids) != len(set(fk_org_uuids)):
        logger.error("Duplicate in fk-org uuids", user_uuid=uuid)
        raise DuplicatedITUserError

    # Check if a user exists in fk-org with the MO-persons uuid. In that case we create the fk-org it-account.
    fk_it = await graphql_client.find_f_k_itsystem()
    try:
        fk_it_uuid = one(fk_it.objects).uuid
    except ValueError:
        raise ITSystemError
    if (
        settings.check_existing_fk_user
        and len(it_users) == 1
        and len(fk_org_users) == 0
    ):
        try:
            current = await os2sync_client.os2sync_get_user(uuid=uuid)
        except KeyError:
            logger.info("User not found in fk-org")
            current = None

        if current:
            if dry_run:
                fk_org_users = [
                    ReadUserITAccountsEmployeesObjectsCurrentFkOrgUuids(
                        uuid=uuid4(),
                        user_key=one(it_users).external_id,  # type: ignore
                        external_id=str(uuid),
                    )
                ]
            else:
                await graphql_client.create_i_t_user(
                    external_id=str(uuid),
                    itsystem=fk_it_uuid,
                    person=uuid,
                    user_key=one(it_users).external_id,  # type: ignore
                    from_=datetime.now(timezone.utc),
                )
                fk_org_users, _ = await read_fk_users_from_person(
                    graphql_client=graphql_client,
                    uuid=uuid,
                    it_user_keys=settings.it_system_user_keys,
                )
    # The code above could be be deleted after the initial runs.

    # Create a fk-org ituser for each it-user if it dosn't already exist
    for it in it_users:
        if (
            it.external_id not in (f.user_key if f else None for f in fk_org_users)
            and not dry_run
        ):
            # allow us to overwrite external_id while keeping the original value for user_key
            user_key = it.external_id

            if settings.randomize_fk_org_uuid:
                # If the user has had a fk-org account in the past for an AD account with the same username, reuse the uuid.
                past_fk_org_uuid = await find_past_account_uuid(
                    graphql_client=graphql_client,
                    person_uuid=uuid,
                    it=it,
                    current_fk_uuids=set(fk_org_uuids),  # type: ignore[arg-type]
                    it_system_user_keys=settings.it_system_user_keys,
                )
                if past_fk_org_uuid:
                    logger.info("Reusing past UUID.", chosen_uuid=past_fk_org_uuid)
                it.external_id = (
                    str(past_fk_org_uuid) if past_fk_org_uuid else str(uuid4())
                )

            await graphql_client.create_i_t_user(
                it.external_id,  # type: ignore
                itsystem=fk_it_uuid,
                person=uuid,
                user_key=user_key,  # type: ignore
                from_=datetime.now(timezone.utc),
            )
    # remove fk-org itusers it the it-user no longer exists.
    for fk in fk_org_users:
        if (
            fk.user_key not in (i.external_id if i else None for i in it_users)
            and not dry_run
        ):
            await graphql_client.terminate_i_t_user(
                uuid=fk.uuid,
                # TODO: ensure it is correct behavior to terminate from yesterday. It is done to ensure
                # FK-org accounts are terminated right away.
                to=date.today() - timedelta(days=1),  # type: ignore
            )
    updates_fk, new_mo_itusers, deletes_fk, delete_mo_itusers = convert_and_filter(
        settings, fk_org_users, it_users
    )
    if not (updates_fk or deletes_fk):
        # If there are no fk-org users to update or delete we attempt to delete the user with the person-uuid.
        # This is just to ensure we cleanup legacy-users that did not have their uuid in an it-user.
        deletes_fk.add(uuid)

    for os2sync_user in updates_fk:
        await os2sync_client.update_user(os2sync_user)
    for deleted_user_uuid in deletes_fk:
        await os2sync_client.delete_user(deleted_user_uuid)
    return updates_fk, deletes_fk


@handle_exclusively_decorator(key=lambda uuid, *_, **__: uuid)
async def sync_orgunit(
    uuid: UUID,
    settings: Settings,
    graphql_client: GraphQLClient,
    os2sync_client: OS2SyncClient,
) -> OrgUnit | None:
    res = await graphql_client.read_orgunit(uuid=uuid)
    if not res.objects:
        await os2sync_client.delete_orgunit(uuid)
        return None
    orgunit_data = one(res.objects).current
    if not orgunit_data:
        await os2sync_client.delete_orgunit(uuid)
        return None
    try:
        os2sync_orgunit = mo_orgunit_to_os2sync(
            settings=settings, orgunit_data=orgunit_data
        )
    except UnitNotRelevantError:
        logger.info("Unit not found relevant for os2sync", unit_uuid=uuid)
        await os2sync_client.delete_orgunit(uuid)
        return None

    await os2sync_client.update_org_unit(os2sync_orgunit.Uuid, org_unit=os2sync_orgunit)
    return os2sync_orgunit


def filter_relevant_orgunit(settings: Settings, orgunit_data: UnitFields) -> bool:
    uuid = orgunit_data.uuid
    log = logger.bind(uuid=uuid)
    # Root unit is always relevant
    if uuid == settings.top_unit_uuid:
        log.info("Unit is top_unit_uuid, relevant")
        return True
    # There can only be one root in fk-org
    if orgunit_data.parent is None:
        log.info("Unit has no parent and is not top_unit, not relevant")
        return False
    ancestor_uuids = {a.uuid for a in orgunit_data.ancestors}
    # Ensure the unit is in the correct part of the tree
    if settings.top_unit_uuid not in ancestor_uuids:
        log.info("Unit is not under top_unit_uuid, not relevant")
        return False

    # Ensure the unit or any of it's ancestors are not filtered
    if uuid in settings.filter_orgunit_uuid or any(
        u in ancestor_uuids for u in settings.filter_orgunit_uuid
    ):
        log.info("Unit or ancestor is in filter_orgunit_uuid, not relevant")
        return False
    # If the unit has an fk-org account it is considered relevant
    # This enables syncing specific units outside the usually relevant hierarchies
    if orgunit_data.itusers:
        log.info("Unit has fk-org it-account, relevant")
        return True
    # Ensure the unit has the correct org_unit_hierarchy (if relevant)
    if settings.filter_hierarchy_names:
        if (
            not orgunit_data.org_unit_hierarchy_model
            or orgunit_data.org_unit_hierarchy_model.name
            not in settings.filter_hierarchy_names
        ):
            log.info(
                "Unit hierarchy not in filter_hierarchy_names, not relevant",
                hierarchy=orgunit_data.org_unit_hierarchy_model.name
                if orgunit_data.org_unit_hierarchy_model
                else None,
            )
            return False
    # Ensure the unit level or type is not ignored
    if (
        orgunit_data.org_unit_level
        and orgunit_data.org_unit_level.uuid in settings.ignored_unit_levels
    ):
        log.info(
            "Unit level is ignored, not relevant",
            level=orgunit_data.org_unit_level.uuid,
        )
        return False
    if (
        orgunit_data.unit_type
        and orgunit_data.unit_type.uuid in settings.ignored_unit_types
    ):
        log.info(
            "Unit type is ignored, not relevant",
            unit_type=orgunit_data.unit_type.uuid,
        )
        return False
    # If all above checks are ok, the unit is relevant to sync to os2sync
    log.info("Unit passed all filters, relevant")
    return True


def find_fk_org_uuid(
    unit: ReadOrgunitOrgUnitsObjectsCurrent | UnitFieldsParent,
):
    fk_org_account = only(unit.itusers)
    return fk_org_account.user_key if fk_org_account else unit.uuid


def mo_orgunit_to_os2sync(
    settings: Settings, orgunit_data: ReadOrgunitOrgUnitsObjectsCurrent
) -> OrgUnit:
    if not filter_relevant_orgunit(settings=settings, orgunit_data=orgunit_data):
        raise UnitNotRelevantError()
    unit_fk_org_uuid = find_fk_org_uuid(orgunit_data)
    parent_fk_org_uuid = (
        find_fk_org_uuid(orgunit_data.parent) if orgunit_data.parent else None
    )
    kle_numbers = (
        {n.uuid for k in orgunit_data.kles for n in k.kle_number}
        if settings.enable_kle
        else set()
    )
    # We can only sync one manager:
    manager = first(orgunit_data.managers, default=None)
    # A manager is always one person
    manager_person = (
        only(manager.person)
        if manager is not None and manager.person is not None
        else None
    )
    manager_uuid = (
        UUID(first(manager_person.itusers).external_id)
        if manager_person is not None and manager_person.itusers
        else None
    )

    ## Reuse old logic for selecting addresses. Create an empty dictionary which is then mutated by addresses_to_orgunit to include the correct os2sync-field to address mapping.
    addresses: dict[str, str] = dict()
    addresses_to_orgunit(
        addresses,
        addresses=jsonable_encoder(orgunit_data.addresses),
        landline_scope_classes=settings.landline_scope_classes,
    )

    return OrgUnit(
        Uuid=unit_fk_org_uuid,
        Name=orgunit_data.name,
        ParentOrgUnitUuid=parent_fk_org_uuid,
        Tasks=kle_numbers,
        ManagerUuid=manager_uuid if settings.sync_managers else None,
        **addresses,  # type: ignore[arg-type]
    )


def find_object_unit(
    object_info: FindAddressUnitOrPersonAddresses
    | FindItuserUnitOrPersonItusers
    | FindManagerUnitManagers
    | FindKLEUnitItusers,
) -> set[UUID]:
    # If objects is empty, return empty set to avoid `one` ValueError
    if not object_info.objects:
        return set()

    validities = one(object_info.objects).validities  # type: ignore [attr-defined]
    org_unit_uuids = {
        o.uuid for org in validities if org.org_unit for o in org.org_unit
    }
    return org_unit_uuids


def find_object_person(
    object_info: FindAddressUnitOrPersonAddresses
    | FindItuserUnitOrPersonItusers
    | FindEngagementPersonEngagements,
) -> set[UUID]:
    # If objects is empty, return empty set to avoid `one` ValueError
    if not object_info.objects:
        return set()

    validities = one(object_info.objects).validities  # type: ignore [attr-defined]
    person_uuids = {o.uuid for org in validities if org.person for o in org.person}
    return person_uuids


async def find_fk_itsystem_uuid(graphql_client: GraphQLClient):
    res = await graphql_client.find_f_k_itsystem()
    return one(res.objects).uuid


async def find_active_accounts(graphql_client: GraphQLClient, limit: int) -> set[UUID]:
    active_accounts: set[UUID] = set()
    cursor: str | None = None
    while True:
        fk_accounts_in_MO = await graphql_client.find_all_f_k_itusers(
            cursor=cursor, limit=limit
        )
        for account in fk_accounts_in_MO.objects:
            if account.current and account.current.external_id:
                active_accounts.add(UUID(account.current.external_id))
        cursor = fk_accounts_in_MO.page_info.next_cursor
        if cursor is None:
            break
    return active_accounts
