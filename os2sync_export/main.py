@fastapi_router.post(
    "/trigger/user/{uuid}", response_model=tuple[list[User], set[UUID]]
)
async def trigger_user(
    uuid: UUID,
    settings: Settings_,
    graphql_session: LegacyGraphQLSession,
    graphql_client: GraphQLClient,
    dry_run: bool = False,
    new: bool = False,
) -> tuple[list[User], set[UUID]]:
    os2sync_client = get_os2sync_client(
        settings=settings, session=None, dry_run=dry_run
    )
    try:
        if settings.new or new:
            return await sync_mo_user_to_fk_org(
                graphql_client=graphql_client,
                settings=settings,
                os2sync_client=os2sync_client,
                uuid=uuid,
                dry_run=dry_run,
            )
        sts_users = await get_sts_user(
            str(uuid),
            graphql_session=graphql_session,
            settings=settings,
        )
    except ValueError:
        raise HTTPException(status_code=404, detail="User not found")

    await os2sync_client.update_users(uuid, sts_users)
    logger.info(f"Synced user to fk-org: {uuid}")

    return [User(**u) for u in sts_users if u["Positions"]], set(
        u["Uuid"] for u in sts_users if not u["Positions"]
    )


@fastapi_router.post(
    "/trigger/orgunit/{uuid}", status_code=200, response_model=OrgUnit | None
)
async def trigger_orgunit(
    uuid: UUID,
    settings: Settings_,
    graphql_client: GraphQLClient,
    graphql_session: LegacyGraphQLSession,
    dry_run: bool = False,
    new: bool = False,
) -> OrgUnit | None:
    os2sync_client = get_os2sync_client(
        settings=settings, session=None, dry_run=dry_run
    )

    if settings.new or new:
        return await sync_orgunit(
            settings=settings,
            graphql_client=graphql_client,
            os2sync_client=os2sync_client,
            uuid=uuid,
        )

    sts_org_unit = await get_sts_orgunit(
        uuid, settings=settings, graphql_session=graphql_session
    )

    await os2sync_client.update_org_unit(uuid, sts_org_unit)
    logger.info(f"Synced org_unit to fk-org: {uuid}")
    return sts_org_unit


def create_fastramqpi(**kwargs) -> FastRAMQPI:
    settings: Settings = Settings(**kwargs)
    mo_listners = [
        Listener(
            namespace="mo",
            user_key=f"os2sync_export_{object_type}",
            routing_key=f"{object_type}",
            path=f"/event/{object_type}",
        )
        for object_type in (
            "address",
            "engagement",
            "ituser",
            "kle",
            "manager",
            "org_unit",
            "person",
        )
    ]
    internal_listners = [
        Listener(
            namespace="os2sync_export",
            user_key="os2sync_export_person",
            routing_key="person",
            path="/sync/person",
        ),
        Listener(
            namespace="os2sync_export",
            user_key="os2sync_export_org_unit",
            routing_key="org_unit",
            path="/sync/org_unit",
        ),
    ]
    fastramqpi = FastRAMQPI(
        application_name="os2sync-export",
        settings=settings.fastramqpi,
        graphql_version=25,
        graphql_client_cls=GraphQLClient_,
        graphql_events=GraphQLEvents(
            declare_namespaces=[
                Namespace(name="os2sync_export"),
            ],
            declare_listeners=mo_listners + internal_listners,
        ),
    )

    fastramqpi.add_context(
        settings=settings,
        os2sync_client=WritableOS2SyncClient(settings=settings),
    )

    app = fastramqpi.get_app()
    app.include_router(fastapi_router)

    return fastramqpi


def create_app() -> FastAPI:
    fastramqpi = create_fastramqpi()
    return fastramqpi.get_app()
