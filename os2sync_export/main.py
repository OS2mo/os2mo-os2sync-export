@fastapi_router.post("/sync/person")
async def sync_person(
    event_uuid: Event[UUID],
    settings: Settings_,
    graphql_session: LegacyGraphQLSession,
    graphql_client: GraphQLClient,
    os2sync_client: OS2SyncClient_,
) -> None:
    uuid = event_uuid.subject
    if settings.new:
        await sync_mo_user_to_fk_org(
            graphql_client=graphql_client,
            settings=settings,
            os2sync_client=os2sync_client,
            uuid=uuid,
        )
        return
    try:
        sts_users = await get_sts_user(
            str(uuid),
            graphql_session=graphql_session,
            settings=settings,
        )
        logger.info(f"Event registered for person with {uuid=}", fk_org_users=sts_users)
    except ValueError:
        await os2sync_client.delete_user(uuid)
        logger.info(f"No fk-org user was found for {uuid=}. Deleting from fk-org")
    else:
        await os2sync_client.update_users(uuid, sts_users)


@fastapi_router.post("/sync/org_unit")
async def sync_org_unit(
    event_uuid: Event[UUID],
    settings: Settings_,
    graphql_session: LegacyGraphQLSession,
    graphql_client: GraphQLClient,
    os2sync_client: OS2SyncClient_,
) -> None:
    uuid = event_uuid.subject
    if settings.new:
        await sync_orgunit(
            settings=settings,
            graphql_client=graphql_client,
            os2sync_client=os2sync_client,
            uuid=uuid,
        )
    else:
        sts_org_unit = None
        if await is_relevant(graphql_session, uuid, settings):
            try:
                sts_org_unit = await get_sts_orgunit(
                    uuid, settings=settings, graphql_session=graphql_session
                )
            except ValueError:
                logger.info(f"Event registered but no org_unit was found with {uuid=}")
                await os2sync_client.delete_orgunit(uuid)
        if sts_org_unit is None:
            await os2sync_client.delete_orgunit(uuid)
        else:
            await os2sync_client.upsert_org_unit(sts_org_unit)

    logger.info(f"Synced org_unit to fk-org: {uuid=}, now checking engagements")
    employees = await find_employees(graphql_session, uuid)
    for e in employees:
        await add_person_event(graphql_client, e)


