@pytest.mark.integration_test
async def test_account_with_no_relevant_engagement(
    graphql_client: GraphQLClient,
    create_person,
    create_engagements,
    create_AD_itsystem,
    create_FK_itsystem,
    set_settings,
) -> None:
    # Arrange
    # Set top_unit_uuid to a new uuid to ensure the engagement is not considered relevant.
    settings = set_settings(top_unit_uuid=uuid4())
    adguid = uuid4()
    fk_org_uuid = uuid4()
    os2sync_mock = AsyncMock()
    person_uuid = create_person.uuid
    # AD users
    await graphql_client.testing__ituser_create(
        input=ITUserCreateInput(
            person=person_uuid,
            user_key="AD-username 1",
            external_id=str(adguid),
            engagements=[e.uuid for e in create_engagements],
            itsystem=create_AD_itsystem,
            validity=RAValidityInput(from_=datetime(1970, 1, 1), to=None),  # type: ignore
        )
    )
    # Create an fk-org user and check that it will not be terminated

    fk_account = await graphql_client.testing__ituser_create(
        input=ITUserCreateInput(
            uuid=uuid4(),
            person=person_uuid,
            user_key=str(adguid),
            external_id=str(fk_org_uuid),
            itsystem=create_FK_itsystem,
            validity=RAValidityInput(from_=datetime(1970, 1, 1), to=None),  # type: ignore
        )
    )
    # Act
    await sync_mo_user_to_fk_org(
        uuid=person_uuid,
        graphql_client=graphql_client,
        settings=settings,
        os2sync_client=os2sync_mock,
    )
    # Assert
    os2sync_mock.update_user.assert_not_called()
    os2sync_mock.delete_user.assert_called_once_with(fk_org_uuid)

    # Check that the expected it-accounts exists in MO
    fk_accounts, it_accounts = await read_fk_users_from_person(
        graphql_client=graphql_client,
        uuid=person_uuid,
        it_user_keys=["AD"],
    )
    assert len(it_accounts) == 1
    # Even though the engagement is no longer relevant we keep the fk-org account
    assert fk_accounts == [
        ReadUserITAccountsEmployeesObjectsCurrentFkOrgUuids(
            uuid=fk_account.uuid, user_key=str(adguid), external_id=str(fk_org_uuid)
        )
    ]


