@pytest.mark.integration_test
async def test_past_account_uuid_dont_reuse_twice(
    graphql_client: GraphQLClient,
    mock_settings,
    create_person,
    create_engagements,
    create_AD_itsystem,
    create_FK_itsystem,
    set_settings,
) -> None:
    """Ensure we don't use a fk-org uuid if the same uuid is already used in another current fk-org account."""
    # Arrange
    settings: Settings = set_settings(randomize_fk_org_uuid=True)

    current_adguid_1 = uuid4()
    current_adguid_2 = uuid4()
    ad_username = "AD username "
    expected_fk_org_uuid_1 = uuid4()
    expected_fk_org_uuid_2 = uuid4()

    os2sync_mock = AsyncMock()
    person_uuid = create_person.uuid

    # Create two AD accounts with the same username
    await graphql_client.testing__ituser_create(
        input=ITUserCreateInput(
            person=person_uuid,
            user_key=ad_username,
            external_id=str(current_adguid_1),
            engagements=[e.uuid for e in create_engagements],
            itsystem=create_AD_itsystem,
            validity=RAValidityInput(
                from_=datetime(2020, 1, 1, 0, 0, 0, tzinfo=UTC), to=None
            ),  # type: ignore
        )
    )
    await graphql_client.testing__ituser_create(
        input=ITUserCreateInput(
            person=person_uuid,
            user_key=ad_username,
            external_id=str(current_adguid_2),
            engagements=[e.uuid for e in create_engagements],
            itsystem=create_AD_itsystem,
            validity=RAValidityInput(
                from_=datetime(2020, 1, 1, 0, 0, 0, tzinfo=UTC), to=None
            ),  # type: ignore
        )
    )
    # Create one of the fk-org accounts
    await graphql_client.testing__ituser_create(
        input=ITUserCreateInput(
            person=person_uuid,
            user_key=str(current_adguid_1),
            external_id=str(expected_fk_org_uuid_1),
            engagements=[e.uuid for e in create_engagements],
            itsystem=create_FK_itsystem,
            validity=RAValidityInput(
                from_=datetime(2010, 1, 1, 0, 0, 0, tzinfo=UTC),
                to=None,
            ),  # type: ignore
        )
    )

    # Act
    with patch("os2sync_export.os2mo_gql.uuid4", return_value=expected_fk_org_uuid_2):
        await sync_mo_user_to_fk_org(
            uuid=person_uuid,
            graphql_client=graphql_client,
            settings=settings,
            os2sync_client=os2sync_mock,
        )

    assert len(os2sync_mock.update_user.call_args) == 2
    os2sync_mock.delete_user.assert_not_called()

    # Check that the expected it-accounts exists in MO
    fk_accounts, it_accounts = await read_fk_users_from_person(
        graphql_client=graphql_client,
        uuid=person_uuid,
        it_user_keys=settings.it_system_user_keys,
    )
    assert len(it_accounts) == 2

    assert {UUID(f.external_id) for f in fk_accounts} == {
        expected_fk_org_uuid_1,
        expected_fk_org_uuid_2,
    }
